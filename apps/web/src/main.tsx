import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { createBrowserRouter } from 'react-router';
import { App } from './app.js';
import { bindBannerToInvestigation } from './banner/bind-investigation.js';
import { createBuiltInBannerController } from './banner/built-in-causes.js';
import { createApiClient } from './api/client.js';
import { appRoutes } from './routes.js';
import { createClientState } from './state/client-state.js';
import { bindSearchPanel } from './search/search-panel-binder.js';
import { bindFiltersPanel } from './workspace/filters-binder.js';
import { registerFiltersTool } from './workspace/filters-tool.js';
import { registerSearchTool } from './search/search-tool.js';
import { createCytoscapeRenderer } from './canvas/cytoscape-renderer.js';
import { registerBuiltInMenuItems } from './workspace/built-in-menu-items.js';
import { registerBuiltInSlots } from './workspace/built-in-slots.js';
import { registerBuiltInTools } from './workspace/built-in-tools.js';
import { registerBuiltInKeyBindings } from './workspace/built-in-key-bindings.js';
import { createKeyBindingRegistry } from './workspace/key-binding-registry.js';
import { createMenuRegistry } from './workspace/menu-registry.js';
import { createSelectionActionRegistry } from './workspace/selection-actions.js';
import { bindBuiltInEvidence } from './evidence/built-in.js';
import { bindBuiltInInspector } from './inspector/built-in-tabs.js';
import { bindLegend } from './workspace/legend-binder.js';
import { bindSupernodePanel } from './workspace/supernode-panel-binder.js';
import { createPanelRegistryFor } from './workspace/panel-registry.js';
import { createSlotRegistry } from './workspace/slots.js';
import { createToolRegistry } from './workspace/tool-registry.js';
import '@fontsource/inter/latin-400.css';
import '@fontsource/inter/latin-500.css';
import '@fontsource/inter/latin-600.css';
import '@fontsource/inter/latin-ext-400.css';
import '@fontsource/inter/latin-ext-500.css';
import '@fontsource/inter/latin-ext-600.css';
import '@fontsource/ibm-plex-mono/latin-400.css';
import '@fontsource/ibm-plex-mono/latin-ext-400.css';
import '@fontsource/ibm-plex-mono/latin-500.css';
import '@fontsource/ibm-plex-mono/latin-ext-500.css';
import './styles/tokens.css';
import './styles/base.css';
import './styles/controls.css';
import './styles/workspace.css';
import './styles/evidence.css';
import './styles/sources.css';
import './styles/search.css';
import './styles/filters.css';
import './styles/first-run.css';
import './styles/home.css';

const root = document.getElementById('root');
if (root === null) throw new Error('the page has no #root element');
const state = createClientState();
const banner = createBuiltInBannerController();
bindBannerToInvestigation(state, banner);
const slots = createSlotRegistry();
registerBuiltInSlots(slots);
const panels = createPanelRegistryFor(state);
bindLegend(state, panels);
bindSearchPanel(state, panels);
bindFiltersPanel(state, panels);
bindSupernodePanel(state, panels);
const { inspector } = bindBuiltInInspector(state, panels);
const tools = createToolRegistry();
registerBuiltInTools(tools);
registerSearchTool(tools, state);
registerFiltersTool(tools, state);
const menus = createMenuRegistry();
registerBuiltInMenuItems(menus);
bindBuiltInEvidence(state, panels, inspector, menus);
const keyBindings = createKeyBindingRegistry();
registerBuiltInKeyBindings(keyBindings);
const router = createBrowserRouter(appRoutes(createApiClient(), state, banner));
createRoot(root).render(
  <StrictMode>
    <App router={router} state={state} banner={banner} slots={slots} selectionActions={createSelectionActionRegistry()} tools={tools} menus={menus} panels={panels} keyBindings={keyBindings} createRenderer={createCytoscapeRenderer} />
  </StrictMode>,
);
